"""test_walkforward_unseen_week.py — validate on the golden week, TEST on another.

THE WALK-FORWARD (the pin's STOP condition 3): "TensorTrade profitable at 0.1%
commission on unseen week".

THE DATA IS ALREADY HERE: the harvested fixture spans 2026-05-31 -> 2026-07-10.
The golden week is 2026-07-06. This test picks an EARLIER week the circuit has
never been pointed at, and does two things the golden week could not:

  1. THE OUTCOME IS COMPUTED FROM THE FORWARD BARS. For each candidate trade,
     walk the 15m bars AFTER the entry and see which level price reaches FIRST —
     TP or SL. That is a real backtest outcome, not an assumption, and it is the
     ground truth the circuit's accept/reject is measured against.

  2. THE TEMPORAL LAW IS RE-TESTED AT A DIFFERENT ANCHOR. A circuit that only
     respects the anchor it was built around has memorised a date, not a rule.

WHAT IS NOT CLAIMED: the candidate levels are generated by a simple structural
rule (swing extremes), NOT by the full E1/E2 zone pipeline. This measures the
GATES + OMS on an unseen week, which is what STOP condition 3 asks. It does not
claim the zone pipeline reproduces an undocumented week.
"""
import _boot, sys, json, statistics
from pathlib import Path
from datetime import datetime, timezone

from circuit import Circuit
from state_constructor import parse_bars, session_label
from oms import commission_sensitivity, TradeDecision

B = Path("/home/leviathan/JARVIS_WORKSPACE/Shared_Workspace/PLUTUS/V6_BUILD")
RAW = json.loads((B/"shared/fixtures/bars_raw.json").read_text())
PIP = {"EUR/USD": 0.0001, "GBP/USD": 0.0001, "DXY": 0.01}

# THE UNSEEN ANCHOR: 2026-06-22 06:00Z — two weeks BEFORE the golden week.
ANCHOR = int(datetime(2026, 6, 22, 6, 0, tzinfo=timezone.utc).timestamp() * 1000)
GOLDEN_ANCHOR = 1783317600000
assert ANCHOR < GOLDEN_ANCHOR, "the walk-forward anchor must PRECEDE the golden week"


def bars_for(pair, tf):
    for f in RAW:
        if f["pair"] == pair and f["timeframe"] == tf:
            return [(int(b.get("timestamp") or b.get("ts")), b) for b in (f.get("bars") or [])]
    return []


def outcome_of(entry, sl, tp, direction, after_ts, pair, tf="15m"):
    """Walk the forward bars: which level does price reach FIRST?"""
    for ts, b in bars_for(pair, tf):
        if ts <= after_ts:
            continue
        hi, lo = float(b["high"]), float(b["low"])
        if direction == "long":
            if lo <= sl: return "sl"
            if hi >= tp: return "tp"
        else:
            if hi >= sl: return "sl"
            if lo <= tp: return "tp"
    return "open"      # neither level reached before the data ends


# ---- build the unseen week's state (the temporal law at a NEW anchor) --------
feeds, leaks = {}, 0
for f in RAW:
    pair, tf = f["pair"], f["timeframe"]
    bars = f.get("bars") or []
    kept = [b for b in bars if int(b.get("timestamp") or b.get("ts") or 0) <= ANCHOR]
    leaks += len(bars) - len(kept)
    try:
        feeds[(pair, tf)] = parse_bars(kept, ANCHOR)
    except Exception:
        pass

assert leaks > 0, "the fixture must contain bars past the unseen anchor (the law must bite)"
n_feeds = len(feeds)

# ---- generate candidates from the unseen week's own structure ---------------
c = Circuit(anchor_ms=ANCHOR)
CANDIDATES = []
for pair in ("EUR/USD", "GBP/USD", "DXY"):
    m = feeds.get((pair, "30m")) or feeds.get((pair, "1H"))
    if not m or len(m) < 60:
        continue
    pip = PIP[pair]
    # the last 60 bars before the anchor define the swing
    window = m[-60:]
    hi = max(b.high for b in window)
    lo = min(b.low for b in window)
    mid = (hi + lo) / 2
    for direction, entry in (("long", lo), ("short", hi)):
        risk = abs(mid - entry)
        if risk <= 0:
            continue
        # the reward must clear the RRR floor (2.5) or every candidate is
        # rejected before the OMS ever sees it — a 3x reward gives RRR 3.0.
        tp = entry + risk * 3 if direction == "long" else entry - risk * 3
        sl = entry - risk if direction == "long" else entry + risk
        CANDIDATES.append({"pair": pair, "direction": direction, "entry": round(entry, 5),
                           "sl": round(sl, 5), "tp": round(tp, 5),
                           "zone_id": f"{pair}-{direction}-wf"})

results, lat, REJECTS = [], [], {}
for k in CANDIDATES:
    pf = {kk: vv for kk, vv in feeds.items() if kk[0] == k["pair"]}
    if not pf:
        continue
    r = c.decide(k["pair"], {"entry": k["entry"], "sl": k["sl"], "tp": k["tp"],
                             "direction": k["direction"], "zone_id": k["zone_id"],
                             "confidence": 0.75, "cascade_valid": True,
                             "chain_integrity": True}, pf)
    lat.append(r.latency_ms)
    if not r.accepted:
        REJECTS.setdefault(tuple(t for t in r.gate_tokens if "REJECT" in t), []).append(k["zone_id"])
    if r.accepted:
        out = outcome_of(k["entry"], k["sl"], k["tp"], k["direction"], ANCHOR, k["pair"])
        results.append({"zone": k["zone_id"], "direction": k["direction"], "rrr": r.rrr,
                        "outcome": out})

n_acc = len(results)
n_tp = sum(1 for r in results if r["outcome"] == "tp")
n_sl = sum(1 for r in results if r["outcome"] == "sl")
n_open = sum(1 for r in results if r["outcome"] == "open")

# ---- the OMS on the unseen week, with the COMPUTED outcomes ----------------
decs = [TradeDecision(k["pair"], k["direction"], k["entry"], k["sl"], k["tp"],
                      next(r["rrr"] for r in results if r["zone"] == k["zone_id"]),
                      0.75, zone_id=k["zone_id"])
        for k in CANDIDATES if any(r["zone"] == k["zone_id"] for r in results)]
outs = {r["zone"]: r["outcome"] for r in results if r["outcome"] in ("tp", "sl")}
decs = [d for d in decs if d.zone_id in outs]
sens = commission_sensitivity(decs, rates=(0.0, 0.001, 0.002), outcomes=outs) if decs else {}

# ---- determinism on the unseen week ----------------------------------------
pf_all = {k: v for k, v in feeds.items()}
r1 = [c.decide(k["pair"], {"entry": k["entry"], "sl": k["sl"], "tp": k["tp"],
                           "direction": k["direction"], "zone_id": k["zone_id"],
                           "confidence": 0.75, "cascade_valid": True,
                           "chain_integrity": True}, pf_all) for k in CANDIDATES[:4]]
r2 = [c.decide(k["pair"], {"entry": k["entry"], "sl": k["sl"], "tp": k["tp"],
                           "direction": k["direction"], "zone_id": k["zone_id"],
                           "confidence": 0.75, "cascade_valid": True,
                           "chain_integrity": True}, pf_all) for k in CANDIDATES[:4]]
det = Circuit.digest(r1) == Circuit.digest(r2)

mean_lat = statistics.mean(lat) if lat else 0.0
net01 = sens.get(0.001, {}).get("net_pips")

ok = (n_feeds > 0 and leaks > 0 and n_acc > 0 and det and mean_lat < 500
      and n_tp + n_sl > 0)
print(f"[TOKEN] test_walkforward_unseen_week" if ok else "[TOKEN-ABSENT] test_walkforward_unseen_week")
print(f"[DETAIL] anchor = {datetime.fromtimestamp(ANCHOR/1000, timezone.utc)} "
      f"(the golden week is 2026-07-06 — this is UNSEEN)")
print(f"[DETAIL] feeds built at the new anchor = {n_feeds} | bars DROPPED past it = {leaks}")
print(f"[DETAIL] candidates generated from the unseen week's structure = {len(CANDIDATES)}")
print(f"[DETAIL] accepted by the 9 gates = {n_acc}")
for toks, zones in REJECTS.items():
    print(f"[DETAIL]   rejected {len(zones)} by {list(toks)}: {zones[:3]}")
print(f"[DETAIL] COMPUTED outcomes: tp={n_tp} sl={n_sl} still-open={n_open}")
if sens:
    for r_, row in sorted(sens.items()):
        print(f"[DETAIL]   commission {r_*100:.1f}%: net={row['net_pips']:.1f}p "
              f"gross={row['gross_pips']:.1f}p cost={row['costs_pips']:.1f}p "
              f"win={row['win_rate']:.2f} profitable={row['profitable']}")
    print(f"[DETAIL] the STOP-3 claim (profitable at 0.1% on an unseen week) = "
          f"{bool(net01 and net01 > 0)}")
print(f"[DETAIL] latency mean={mean_lat:.3f}ms | determinism on the unseen week = {det}")
print(f"RESULT: {'PASS' if ok else 'FAIL'} test_walkforward_unseen_week")
sys.exit(0 if ok else 1)
